def _run(cmd, **kw):
    kw.setdefault("capture_output", True)
    kw.setdefault("text", True)
    return subprocess.run(cmd, **kw)


def which(binary):
    """PATH + opencode 기본 설치 경로까지 본다 (설치 직후 PATH가 아직 안 잡힌 셸 대응)."""
    found = _run(["/usr/bin/which", binary]).stdout.strip()
    if found:
        return found
    fallback = pathlib.Path.home() / f".{binary}" / "bin" / binary
    return str(fallback) if fallback.is_file() and os.access(fallback, os.X_OK) else ""


def atomic_write(path, content):
    path = pathlib.Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=path.name + ".", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
        os.replace(temporary, str(path))
    except BaseException:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise


def git_ignored(relpath):
    """이 경로가 확실히 Git 밖인가. 판정 불가면 False — 개인 상태는 fail-close 한다."""
    proc = _run(["git", "-C", str(ROOT), "check-ignore", "-q", relpath])
    return proc.returncode == 0


