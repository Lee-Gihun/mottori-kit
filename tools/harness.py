def canary_once(binary, model, timeout):
    """모델 하나를 잰다. (verdict, detail) 반환. verdict: pass|fail|inconclusive|refused|timeout.

    nonce는 실행 동안만 주입 파일(kit-state.md, Git 밖)에 있다 — 그 파일을 첨부로 보내는 것이
    재려는 채널이기 때문이다. 실행이 끝나면(타임아웃·예외 포함) finally가 nonce 없는 본문으로
    덮어쓰고, 원장에는 판정만 남는다. 판정 규칙은 read_stream의 docstring 참고.
    """
    nonce = "KIT-" + uuid.uuid4().hex[:10].upper()
    public_only = not git_ignored(OPENCODE_STATE)
    os.environ["MOTTORI_HOOK_CANARY"] = nonce
    atomic_write(ROOT / OPENCODE_STATE, render_state(public_only=public_only))

    # 상태를 첨부로 붙인다. `instructions` 경로는 v2.0.11에서 로드되지 않는 것이 실측됐고,
    # `open`이 쓰는 것과 같은 파일이라 이 왕복이 그 채널을 그대로 잰다.
    cmd = [binary, "run", "--standalone", "-m", model, "--format", "json",
           "-f", str(ROOT / OPENCODE_STATE),
           "Print only the value that follows HOOK_CANARY: in the attached state. "
           "No other words. If it is absent, print ABSENT."]
    try:
        proc = _run(cmd, cwd=str(ROOT), timeout=timeout)
    except subprocess.TimeoutExpired:
        return "timeout", f"{timeout:.0f}s 안에 응답 없음"
    finally:
        os.environ.pop("MOTTORI_HOOK_CANARY", None)
        atomic_write(ROOT / OPENCODE_STATE, render_state(public_only=public_only))

    text, tools, errors = read_stream(proc.stdout)
    if errors:
        return "refused", errors[0][:160]
    if tools:
        return "inconclusive", "도구 사용: " + ", ".join(sorted(set(tools)))
    if nonce in text:
        return "pass", "도구 사용 0"
    return "fail", (text.strip()[:120] or "(빈 응답)")


def persist_canary(rows, path=None):
    """판정과 시각만 남긴다. 원장에 nonce를 보존하지 않는다 (hook_canary와 같은 규칙)."""
    path = pathlib.Path(path or (ROOT / CANARY_LEDGER))
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
        if payload.get("schema_version") != 1 or not isinstance(payload.get("models"), dict):
            raise ValueError
    except (OSError, ValueError):
        payload = {"schema_version": 1, "models": {}}
    stamp = datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")
    for model, (verdict, detail) in rows.items():
        payload["models"][model] = {"checked_at": stamp, "verdict": verdict, "detail": detail}
    atomic_write(path, json.dumps(payload, ensure_ascii=False, indent=2) + "\n")
    return path


def cmd_verify(args):
    """카나리 왕복. 주입이 '설정에 있다'가 아니라 '모델이 봤다'를 재는 유일한 방법이다.

    `--sweep`는 부를 수 있는 모델을 전부 돌며 표를 만든다. 온디맨드로 모델을 갈아탈 때
    "이 모델이 킷 상태를 실제로 받아서 따르나"를 모델마다 따로 알아야 하기 때문이다.
    """
    if args.runtime != "opencode":
        print(f"{args.runtime} 카나리는 tools/hook_canary.py가 담당한다.")
        return 2
    binary = which("opencode")
    if not binary:
        print("opencode가 없다. 설치 후 다시 실행해라.")
        return 2

    models = available_models(binary) if args.sweep else [args.model]
    if not models:
        print("부를 수 있는 모델이 없다. `opencode auth login` 먼저.")
        return 2

    rows = {}
    for model in models:
        verdict, detail = canary_once(binary, model, args.timeout)
        rows[model] = (verdict, detail)
        mark = {"pass": "PASS", "fail": "FAIL", "inconclusive": "INCONC",
                "refused": "REFUSED", "timeout": "TIMEOUT"}[verdict]
        print(f"{mark:8} {model}  {detail}")
    ledger = persist_canary(rows)
    passed = sum(1 for v, _ in rows.values() if v == "pass")
    print(f"\n{passed}/{len(rows)} 모델이 킷 상태를 받았다 · 원장 {ledger.relative_to(ROOT).as_posix()}")
    if passed == 0:
        print("  판정 불가·거부가 전부면 주입이 아니라 모델·티어 문제일 수 있다.")
    return 0 if passed else 1


def read_stream(stream):
    """모델 답변·도구 호출·오류를 나눠 읽는다.

    도구 호출을 따로 세는 이유: 주입 본문이 **파일**인 하네스에서는 모델이 grep·read로 같은
    파일을 찾아 주입 없이도 nonce를 답할 수 있다 (2026-09-21 실측: 첫 실험이 그렇게 오염됐다).
    도구를 껐더니 무료 티어가 실행을 거부해서(403), 끄는 대신 **도구를 쓴 실행은 PASS로 세지
    않는다**. 증거가 약해지는 쪽이 아니라 판정을 유보하는 쪽으로 실패한다.
    """
    text, tools, errors = [], [], []
    for line in (stream or "").splitlines():
        line = line.strip()
        if not line.startswith("{"):
            continue
        try:
            event = json.loads(line)
        except ValueError:
            continue
        kind = event.get("type")
        part = event.get("part") or {}
        if kind == "text":
            text.append(str(part.get("text", "")))
        elif kind == "tool_use":
            tools.append(str(part.get("tool", "?")))
        elif kind == "error":
            errors.append(str((event.get("error") or {}).get("message", "error")))
    return "\n".join(text), tools, errors


def seed_prompt(state):
    return ("아래는 킷이 이 세션에 심은 현재 상태다. 대화 맥락과 충돌하면 이것이 정본이다.\n"
            "요약·기억이 아니라 이 본문을 근거로 삼아라.\n\n" + state)


def cmd_open(args):
    """상태를 굽고 하네스를 띄운다. opencode는 첫 프롬프트로 상태를 심는다.

    훅이 없는 하네스에서 유일하게 확인된 주입 경로다. 대가가 있다: 세션이 뜨자마자 한 턴을
    쓴다. 직접 `opencode`를 친 세션에는 상태가 안 들어간다 — 그건 gap으로 선언돼 있다.
    """
    binary = which(args.runtime)
    if not binary:
        print(f"{args.runtime}가 PATH에 없다.")
        return 2
    if args.runtime != "opencode":
        os.execv(binary, [binary] + args.rest)
    cmd_refresh(args)
    state = (ROOT / OPENCODE_STATE).read_text(encoding="utf-8")
    os.execv(binary, [binary, "--prompt", seed_prompt(state)] + args.rest)


def main(argv=None):
    parser = argparse.ArgumentParser(description="하네스 배선의 단일 진입점")
    sub = parser.add_subparsers(dest="cmd", required=True)

    sub.add_parser("status", help="설치·배선·역할 커버리지").set_defaults(func=cmd_status)

    p_install = sub.add_parser("install", help="이 인스턴스에 배선을 깐다")
    p_install.add_argument("runtime", choices=sorted(RUNTIMES))
    p_install.set_defaults(func=cmd_install)

    sub.add_parser("check", help="생성물 parity (모델 호출 없음)").set_defaults(func=cmd_check)
    sub.add_parser("refresh", help="주입용 상태 파일 재생성").set_defaults(func=cmd_refresh)

    p_verify = sub.add_parser("verify", help="카나리 왕복 실측")
    p_verify.add_argument("runtime", choices=sorted(RUNTIMES))
    p_verify.add_argument("--model", default=os.environ.get("MOTTORI_OPENCODE_MODEL", DEFAULT_OPENCODE_MODEL))
    p_verify.add_argument("--sweep", action="store_true", help="부를 수 있는 모델을 전부 잰다")
    p_verify.add_argument("--timeout", type=float, default=300.0)
    p_verify.set_defaults(func=cmd_verify)

    p_open = sub.add_parser("open", help="상태를 굽고 하네스를 띄운다")
    p_open.add_argument("runtime", choices=sorted(RUNTIMES))
    p_open.add_argument("rest", nargs=argparse.REMAINDER)
    p_open.set_defaults(func=cmd_open)

    args = parser.parse_args(argv)
    return args.func(args)


