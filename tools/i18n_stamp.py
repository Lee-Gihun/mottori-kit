@dataclass(frozen=True)
class Pair:
    canonical: Path
    locale: Path
    source: Path
    target: Path
    direction: str
    state: str


@dataclass(frozen=True)
class Stale:
    target: str
    source: str | None
    message: str


@dataclass(frozen=True)
class Report:
    pairs: tuple[Pair, ...]
    stale: tuple[Stale, ...]
    pending: tuple[str, ...]
    # Disagreement between ko/INDEX.md and the pairs on disk. Kept apart from ``stale``
    # so callers that check translation stamps alone are not affected by the index.
    index: tuple[str, ...] = ()


def relative(path: Path, root: Path) -> str:
    try:
        return path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError as error:
        raise ValueError(f"path is outside root: {path}") from error


def normalized_bytes(path: Path) -> bytes:
    """Normalize line-ending representation without changing Markdown whitespace."""
    text = path.read_bytes().decode("utf-8").replace("\r\n", "\n").replace("\r", "\n")
    return text.encode("utf-8")


def content_hash(path: Path) -> str:
    return hashlib.sha256(normalized_bytes(path)).hexdigest()


def pending_paths(root: Path) -> tuple[tuple[str, ...], list[Stale]]:
    path = root / PENDING_PATH
    if not path.is_file():
        return (), [Stale(PENDING_PATH, None, f"{PENDING_PATH}: pending-file missing")]
    entries: list[str] = []
    stale: list[Stale] = []
    seen: set[str] = set()
    for number, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        entry = raw.strip()
        if not entry or entry.startswith("#"):
            continue
        if entry in seen:
            stale.append(
                Stale(entry, None, f"{PENDING_PATH}:{number}: duplicate pending entry: {entry}")
            )
            continue
        seen.add(entry)
        entries.append(entry)
    return tuple(entries), stale


def locale_rel(canonical_rel: str) -> str:
    """Return the Korean path for an English repository-relative path."""
    return f"{LOCALE_DIR}/{canonical_rel}"


def canonical_rel_for(locale: str) -> str | None:
    """Return the English path for a Korean path under ko/, or None outside it."""
    prefix = LOCALE_DIR + "/"
    return locale[len(prefix):] if locale.startswith(prefix) else None


def locale_documents(root: Path) -> set[str]:
    """Return Korean translation files under ko/, excluding the index and instance files."""
    base = root / LOCALE_DIR
    if not base.is_dir():
        return set()
    found = set()
    for path in base.rglob("*.md"):
        rel = relative(path, root)
        canonical = canonical_rel_for(rel)
        if rel == INDEX_PATH or canonical is None or not path.is_file():
            continue
        if canonical in INSTANCE_FILES or canonical.startswith(EXCLUDED_PREFIXES):
            continue
        found.add(rel)
    return found


def is_korean_source(canonical_rel: str) -> bool:
    return canonical_rel in KO_SOURCE_FILES or canonical_rel.startswith("system/lenses/")


def make_pair(canonical: Path, locale: Path, root: Path, state: str = "completed") -> Pair:
    canonical_rel = relative(canonical, root)
    if is_korean_source(canonical_rel):
        return Pair(canonical, locale, locale, canonical, "ko", state)
    return Pair(canonical, locale, canonical, locale, "en", state)


def canonical_set(root: Path, required_pairs: set[str]) -> list[str]:
    """Return English paths that must have a pair: the inventory plus every file under ko/."""
    names = set(required_pairs)
    names.update(canonical_rel_for(rel) or rel for rel in locale_documents(root))
    return sorted(names)


def discover_pairs(
    root: Path, pending: set[str], required_pairs: set[str], pair_states: dict[str, str]
) -> tuple[list[Pair], list[Stale]]:
    pairs: list[Pair] = []
    stale: list[Stale] = []
    for canonical_rel in canonical_set(root, required_pairs):
        canonical = root / canonical_rel
        locale = root / locale_rel(canonical_rel)
        state = pair_states.get(canonical_rel, "completed")
        pair = make_pair(canonical, locale, root, state)
        listed_pending = canonical_rel in pending or locale_rel(canonical_rel) in pending
        if state not in {"completed", "pending"}:
            stale.append(
                Stale(
                    relative(pair.target, root),
                    relative(pair.source, root),
                    f"{canonical_rel}: invalid pair inventory state: {state}",
                )
            )
            continue
        if state == "pending":
            if not listed_pending:
                stale.append(
                    Stale(
                        relative(pair.target, root),
                        relative(pair.source, root),
                        f"{canonical_rel}: inventory state is pending but pending entry is missing",
                    )
                )
            continue
        if listed_pending:
            target_rel = relative(pair.target, root)
            stale.append(
                Stale(
                    target_rel,
                    relative(pair.source, root),
                    f"{target_rel}: completed pair cannot be pending without an explicit inventory transition",
                )
            )
            continue
        if not pair.source.is_file():
            target_rel = relative(pair.target, root)
            stale.append(
                Stale(
                    target_rel,
                    relative(pair.source, root),
                    f"{target_rel}: source file missing: {relative(pair.source, root)}",
                )
            )
            continue
        if not pair.target.is_file():
            stale.append(
                Stale(
                    relative(pair.target, root),
                    relative(pair.source, root),
                    f"{relative(pair.target, root)}: translated file missing",
                )
            )
            continue
        pairs.append(pair)
    return pairs, stale


def expected_stamp(pair: Pair, root: Path) -> str:
    """Return the stamp line; ``source`` is the repository-relative path of the source file."""
    return (
        f"<!-- source: {relative(pair.source, root)} sha256:{content_hash(pair.source)} "
        f"source-of-truth: {pair.direction} -->"
    )


def pair_stale(pair: Pair, root: Path) -> Stale | None:
    target_rel = relative(pair.target, root)
    source_rel = relative(pair.source, root)
    lines = pair.target.read_text(encoding="utf-8").splitlines()
    stamp_lines = [line for line in lines if STAMP_RE.fullmatch(line)]
    if not lines or STAMP_RE.fullmatch(lines[0]) is None:
        return Stale(target_rel, source_rel, f"{target_rel}: missing translation stamp")
    if len(stamp_lines) != 1:
        return Stale(target_rel, source_rel, f"{target_rel}: multiple translation stamps")
    stamp = STAMP_RE.fullmatch(lines[0])
    assert stamp is not None
    if stamp.group("source") != source_rel:
        return Stale(
            target_rel,
            source_rel,
            f"{target_rel}: stamp source is {stamp.group('source')}; expected {source_rel}",
        )
    if stamp.group("direction") != pair.direction:
        return Stale(
            target_rel,
            source_rel,
            f"{target_rel}: source-of-truth is {stamp.group('direction')}; expected {pair.direction}",
        )
    if stamp.group("digest") != content_hash(pair.source):
        return Stale(target_rel, source_rel, f"{target_rel}: source hash changed ({source_rel})")
    return None


def check(
    root: Path = ROOT,
    required_pairs: set[str] | None = None,
    pair_states: dict[str, str] | None = None,
) -> Report:
    root = root.resolve()
    pending, stale = pending_paths(root)
    required = REQUIRED_LOCALE_PAIRS if required_pairs is None else required_pairs
    states = PAIR_INVENTORY if pair_states is None else pair_states
    pairs, pair_discovery_stale = discover_pairs(root, set(pending), required, states)
    stale.extend(pair_discovery_stale)
    stale.extend(item for pair in pairs if (item := pair_stale(pair, root)) is not None)
    index = index_issues(root, render_index(root, stale, required, states))
    return Report(tuple(pairs), tuple(stale), pending, index)


def index_rows(
    root: Path, stale: list[Stale], required_pairs: set[str], pair_states: dict[str, str]
) -> list[tuple[str, str, str, str]]:
    """Return (English path, Korean path, source of truth, state) for every pair.

    State is ``pending`` for an inventory transition, ``missing`` when either file is
    absent, ``stale`` when the translation stamp no longer matches, and ``current``
    otherwise. An invalid inventory state is reported by ``check`` and shown as such.
    """
    stale_paths = {item.target for item in stale} | {item.source for item in stale if item.source}
    rows = []
    for canonical_rel in canonical_set(root, required_pairs):
        korean = locale_rel(canonical_rel)
        state = pair_states.get(canonical_rel, "completed")
        direction = "ko" if is_korean_source(canonical_rel) else "en"
        if state == "pending":
            status = "pending"
        elif state != "completed":
            status = f"invalid ({state})"
        elif not (root / canonical_rel).is_file() or not (root / korean).is_file():
            status = "missing"
        elif canonical_rel in stale_paths or korean in stale_paths:
            status = "stale"
        else:
            status = "current"
        rows.append((canonical_rel, korean, direction, status))
    return rows


def render_index(
    root: Path, stale: list[Stale], required_pairs: set[str], pair_states: dict[str, str]
) -> str:
    """Render ko/INDEX.md. Links are relative to ko/ so the link checker verifies both columns."""
    lines = [
        "# Korean translation index",
        "",
        f"Generated by `{INDEX_COMMAND}`. Do not edit by hand: `python3 tools/i18n_stamp.py check`",
        "fails when this table differs from the files. Each Korean file lives at `ko/<path>` for the",
        "English file at `<path>`. Source of truth `en` means the Korean file is a translation;",
        "`ko` means the English file is translated from the Korean one.",
        "",
        "| English | Korean | Source of truth | State |",
        "|---|---|---|---|",
    ]
    for english, korean, direction, status in index_rows(root, stale, required_pairs, pair_states):
        korean_link = korean[len(LOCALE_DIR) + 1:]
        lines.append(f"| [{english}](../{english}) | [{korean}]({korean_link}) | {direction} | {status} |")
    return "\n".join(lines) + "\n"


def index_issues(root: Path, wanted: str) -> tuple[str, ...]:
    path = root / INDEX_PATH
    if not path.is_file():
        return (f"{INDEX_PATH}: pair index missing; run {INDEX_COMMAND}",)
    if normalized_bytes(path).decode("utf-8") != wanted:
        return (f"{INDEX_PATH}: pair index differs from the files; run {INDEX_COMMAND}",)
    return ()


def write_index(
    root: Path = ROOT,
    required_pairs: set[str] | None = None,
    pair_states: dict[str, str] | None = None,
) -> Path:
    """Regenerate ko/INDEX.md from the pairs on disk and return its path."""
    root = root.resolve()
    required = REQUIRED_LOCALE_PAIRS if required_pairs is None else required_pairs
    states = PAIR_INVENTORY if pair_states is None else pair_states
    report = check(root, required, states)
    path = root / INDEX_PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    atomic_write(path, render_index(root, list(report.stale), required, states))
    return path


def atomic_write(path: Path, content: str) -> None:
    """Replace ``path`` atomically, keeping its mode; a new file gets mode 0644."""
    mode = path.stat().st_mode if path.exists() else 0o644
    descriptor, temporary = tempfile.mkstemp(prefix=path.name + ".", dir=str(path.parent))
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    except BaseException:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise


def bind(target: Path, root: Path = ROOT) -> Pair:
    root = root.resolve()
    target = target if target.is_absolute() else root / target
    target = target.resolve()
    target_rel = relative(target, root)
    if not target.is_file():
        raise ValueError(f"translated file does not exist: {target_rel}")
    if not target.name.endswith(".md"):
        raise ValueError("bind target must be X.md or ko/X.md")
    canonical_rel = canonical_rel_for(target_rel) or target_rel
    canonical = root / canonical_rel
    locale = root / locale_rel(canonical_rel)
    pair = make_pair(canonical, locale, root)
    pending, pending_stale = pending_paths(root)
    if pending_stale:
        raise ValueError(pending_stale[0].message)
    if PAIR_INVENTORY.get(canonical_rel) == "pending":
        raise ValueError(
            f"cannot bind pending pair before inventory transition: {canonical_rel}"
        )
    if relative(canonical, root) in set(pending) or target_rel in set(pending):
        raise ValueError(f"cannot bind pending file: {target_rel}")
    if target != pair.target.resolve():
        raise ValueError(
            f"bind expects translated side {relative(pair.target, root)} for source-of-truth {pair.direction}"
        )
    if not pair.source.is_file():
        raise ValueError(f"source file does not exist: {relative(pair.source, root)}")
    text = target.read_text(encoding="utf-8")
    lines = text.splitlines(keepends=True)
    if lines and (STAMP_RE.fullmatch(lines[0].rstrip("\r\n")) or lines[0].startswith("<!-- source: ")):
        text = "".join(lines[1:])
    atomic_write(target, expected_stamp(pair, root) + "\n" + text)
    return pair


def print_report(report: Report, root: Path, include_bound: bool) -> None:
    stale_targets = {item.target for item in report.stale}
    if include_bound:
        for pair in report.pairs:
            target = relative(pair.target, root)
            status = "STALE" if target in stale_targets else "BOUND"
            print(
                f"{status} {target} <- {relative(pair.source, root)} "
                f"(source-of-truth: {pair.direction})"
            )
    pair_targets = {relative(pair.target, root) for pair in report.pairs}
    for item in report.stale:
        if not include_bound or item.target not in pair_targets:
            print(f"STALE {item.message}")
    for pending in report.pending:
        print(f"PENDING {pending}")
    for issue in report.index:
        print(f"STALE {issue}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    subparsers = parser.add_subparsers(dest="command", required=True)
    subparsers.add_parser("check", help="report stale and pending translations")
    bind_parser = subparsers.add_parser("bind", help="bind a completed translation to its source")
    bind_parser.add_argument("target", type=Path, help="translated X.md or ko/X.md")
    subparsers.add_parser("list", help="list locale pairs, directions, and state")
    subparsers.add_parser("index", help=f"regenerate {INDEX_PATH} from the pairs on disk")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    if args.command == "bind":
        try:
            pair = bind(args.target, root)
        except (OSError, UnicodeError, ValueError) as error:
            print(f"ERROR {error}")
            return 2
        print(
            f"BOUND {relative(pair.target, root)} <- {relative(pair.source, root)} "
            f"(source-of-truth: {pair.direction})"
        )
        return 0
    if args.command == "index":
        try:
            path = write_index(root)
        except (OSError, UnicodeError, ValueError) as error:
            print(f"ERROR {error}")
            return 2
        print(f"WROTE {relative(path, root)}")
        return 0
    report = check(root)
    print_report(report, root, include_bound=args.command == "list")
    failed = bool(report.stale or report.index)
    status = "PASS" if not failed else "FAIL"
    print(
        f"i18n stamps: {status} (stale {len(report.stale)}; pending {len(report.pending)}; "
        f"index {'current' if not report.index else 'differs'})"
    )
    return 1 if args.command == "check" and failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
