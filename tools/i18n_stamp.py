#!/usr/bin/env python3
"""Bind each translated Markdown file to its source content hash.

The English document at ``X.md`` pairs with its Korean translation at ``ko/X.md``:
the same repository-relative path under the ``ko/`` directory. ``ko/INDEX.md`` lists
every pair. It is generated by ``index`` and ``check`` fails when it differs from the
pairs on disk, so the table cannot drift from the files.
"""
